export function operationalUiCopy(value: string) {
  return value
    .replace(/RAG-DEMO-[A-Za-z0-9]+:\s*/g, '')
    .replace(/\bE2E\s+/g, '')
    .replace(/실행 기록\s+sim-[A-Za-z0-9-]+\s*가 생성되었습니다\.?/g, '장치 변경 내역을 기록했습니다.')
    .replace(/\bsim-[A-Za-z0-9-]+\b/g, '내부 실행 기록')
    .replace(/시범 운영 (?:recipe|레시피)/gi, '운영 기준')
    .replace(/시범 recipe/gi, '운영 기준')
    .replace(/로컬 검증 환경/g, '운영 기준')
    .replace(/시뮬레이터 정책/g, '운영 정책')
    .replace(/합성 데모/g, '참고 자료')
    .replace(/합성 운영 규칙/g, '운영 규칙')
    .replace(/시뮬레이션 센서/g, '연결된 센서')
    .replace(/센서 시뮬레이터/g, '센서')
    .replace(/MCP 시뮬레이터/g, '장치 연결')
    .replace(/FarmOps MCP 실행/g, '장치 변경')
    .replace(/MCP 실행/g, '장치 변경')
    .replace(/FarmOps MCP/g, '장치 연결')
    .replace(/MCP/g, '장치 연결')
    .replace(/\bcritical\b/gi, '긴급')
    .replace(/\bwarning\b/gi, '주의')
    .replace(/\bnormal\b/gi, '정상')
    .replace(/시뮬레이터/g, '장치')
    .replace(/시뮬레이션 관측/g, '센서 관측')
    .replace(/시뮬레이션/g, '운영')
}
